// Merge tools/gre/part*.json into public/words/ggre.js (the GRE Verbal level).
// Usage: node tools/gre/build_gre.js
const fs = require("fs"), path = require("path");
const dir = __dirname;
const parts = fs.readdirSync(dir).filter(f => /^part\d+\.json$/.test(f)).sort();
const lessons = parts.flatMap(f => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"))).sort((a, b) => a.n - b.n);
const out = {
  name: "GRE",
  longName: "GRE Verbal",
  theme: "Scholar's Tower",
  lessons: lessons.map(l => ({
    title: l.title, icon: l.icon, rule: l.rule, tip: l.tip, examples: l.examples,
    games: ["learn", "match", "tc", "se", "test"],
    words: l.words.map(x => ({ w: x.w, pos: x.pos, s: x.s, m: x.m, syn: x.syn, ant: x.ant, root: x.root })),
    tc: l.tc, se: l.se,
  })),
};
const js = "/* generated by tools/gre/build_gre.js from tools/gre/part*.json — edit those, then re-run */\n" +
  "window.SPELLING_DATA = window.SPELLING_DATA || {};\n" +
  `window.SPELLING_DATA["gre"] = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(dir, "..", "..", "public", "words", "ggre.js"), js);
console.log(`ggre.js: ${out.lessons.length} lessons, ${out.lessons.reduce((a, l) => a + l.words.length, 0)} words, ` +
  `${out.lessons.reduce((a, l) => a + l.tc.length, 0)} TC, ${out.lessons.reduce((a, l) => a + l.se.length, 0)} SE (from ${parts.join(", ")})`);
